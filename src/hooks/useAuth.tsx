import { useState, useEffect, createContext, useContext, ReactNode, useCallback, useRef } from 'react';
import { useQueryClient } from '@tanstack/react-query';
import { supabase } from '@/integrations/supabase/client';

// ????????? Types ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

// Minimal User shape our system needs (not Supabase's full User type)
export interface AppUser {
  id: string;
  username: string;
  name?: string;
  email?: string;
}

export interface AppSession {
  access_token: string;
  token_type: string;
  expires_in: number;
  expires_at: number;
  user: AppUser;
}

interface AuthContextType {
  user: AppUser | null;
  session: AppSession | null;
  loading: boolean;
  userRole: string | null;
  isAuthenticated: boolean;
  signIn: (username: string, password: string) => Promise<{ error: any; role?: string; user?: AppUser }>;
  signUp: (username: string, password: string, name?: string) => Promise<{ error: any; user?: AppUser }>;
  signOut: () => Promise<void>;
  validateSession: () => Promise<boolean>;
  refreshRole: () => Promise<void>;
}

