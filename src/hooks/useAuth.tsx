/**
 * Decode a JWT token payload without verifying signature.
 * Returns null if the token is malformed.
 */
function decodeJwt(token: string): Record<string, any> | null {
  try {
    const base64 = token.split('.')[1];
    if (!base64) return null;
    let padded = base64.replace(/-/g, '+').replace(/_/g, '/');
    while (padded.length % 4) {
      padded += '=';
    }
    const json = decodeURIComponent(
      atob(padded)
        .split('')
        .map((c) => '%' + ('00' + c.charCodeAt(0).toString(16)).slice(-2))
        .join('')
    );
    return JSON.parse(json);
  } catch {
    return null;
  }
}

function getRoleFromToken(token: string): string | null {
  const payload = decodeJwt(token);
  return payload?.role || null;
}

function isTokenExpired(token: string): boolean {
  const payload = decodeJwt(token);
  if (!payload?.exp) return false;
  return Date.now() / 1000 > payload.exp;
}

function getStoredToken(): string | null {
  if (typeof window === 'undefined') return null;
  return localStorage.getItem('sb-token');
}

function getStoredUser(): AppUser | null {
  if (typeof window === 'undefined') return null;
  try {
    const raw = localStorage.getItem('sb-user');
    return raw ? JSON.parse(raw) : null;
  } catch {
    return null;
  }
}

// ????????? Context ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

const AuthContext = createContext<AuthContextType | undefined>(undefined);

export function AuthProvider({ children }: { children: ReactNode }) {
  const [user, setUser] = useState<AppUser | null>(null);
  const [session, setSession] = useState<AppSession | null>(null);
  const [loading, setLoading] = useState(true);
  const [userRole, setUserRole] = useState<string | null>(null);
  const queryClient = useQueryClient();
  const isMountedRef = useRef(true);

  const isAuthenticated = !!user && !!session;

  const clearAuthState = useCallback(() => {
    setUser(null);
    setSession(null);
    setUserRole(null);
    localStorage.removeItem('sb-user');
    localStorage.removeItem('sb-token');
    if (typeof document !== 'undefined') {
      document.cookie = 'sb-token=; expires=Thu, 01 Jan 1970 00:00:00 GMT; path=/; SameSite=Lax';
    }
    queryClient.clear();
  }, [queryClient]);

  // ─── Initialize from localStorage on mount ──────────────────────────────────────────
  useEffect(() => {
    isMountedRef.current = true;

    const initializeAuth = () => {
      try {
        const token = getStoredToken(); // Will be 'httponly-cookie' placeholder if user data exists
        const storedUser = getStoredUser();

        if (!token || !storedUser) {
          setLoading(false);
          return;
        }

        if (typeof document !== 'undefined' && token) {
          const expires = new Date(Date.now() + 7 * 864e5).toUTCString();
          document.cookie = `sb-token=${encodeURIComponent(token)}; expires=${expires}; path=/; SameSite=Lax`;
        }

        const role = getRoleFromToken(token);

        const sessionObj: AppSession = {
          access_token: token,
          token_type: 'bearer',
          expires_in: 604800,
          expires_at: Math.floor(Date.now() / 1000) + 604800,
          user: storedUser,
        };

        if (isMountedRef.current) {
          setUser(storedUser);
          setSession(sessionObj);
          if (role) setUserRole(role);
        }
      } finally {
        if (isMountedRef.current) {
          setLoading(false);
        }
      }
    };

    initializeAuth();

    // Listen to auth state changes from supabase client (handles SIGNED_OUT events)
    const { data: { subscription } } = supabase.auth.onAuthStateChange((event, _session) => {
      if (!isMountedRef.current) return;
      if (event === 'SIGNED_OUT') {
        clearAuthState();
      }
    });

    return () => {
      isMountedRef.current = false;
      subscription.unsubscribe();
    };
  }, [clearAuthState]);

  const refreshRole = useCallback(async () => {
    try {
      const token = getStoredToken();
      if (token && isMountedRef.current) {
        const role = getRoleFromToken(token);
        if (role) {
          setUserRole(role);
        }
      }
    } catch {
      // Silent fail for role refresh
    }
  }, []);

  // ?????? validateSession ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
  const validateSession = useCallback(async (): Promise<boolean> => {
    // SECURITY: Token is in httpOnly cookie ??? validated server-side.
    // We check if user data exists in localStorage as a quick client-side indicator.
    const storedUser = getStoredUser();
    if (!storedUser) {
      clearAuthState();
      return false;
    }
    return true;
  }, [clearAuthState]);

  // ?????? signIn ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
  // Provide a minimal signIn wrapper to align with our local setup
  const signInWithPassword = useCallback(async (credentials: any) => {
    const { data, error } = await supabase.auth.signInWithPassword(credentials);
    if (!error && data.session) {
      const role = getRoleFromToken(data.session.access_token);
      setUser(data.user as any);
      setSession(data.session as any);
      setUserRole(role);
      localStorage.setItem('sb-user', JSON.stringify(data.user));
      localStorage.setItem('sb-token', data.session.access_token);
      if (typeof document !== 'undefined') {
        const expires = new Date(Date.now() + 7 * 864e5).toUTCString();
        document.cookie = `sb-token=${encodeURIComponent(data.session.access_token)}; expires=${expires}; path=/; SameSite=Lax`;
      }
    }
    return { data, error };
  }, []);

  const signIn = async (username: string, password: string) => {
    const { data, error } = await supabase.auth.signInWithPassword({ username, password });

    if (error || !data.session) {
      return { error: error || new Error('No session returned') };
    }

    const role = getRoleFromToken(data.session.access_token);

    if (isMountedRef.current) {
      setUser(data.user as any);
      setSession(data.session as any);
      if (role) setUserRole(role);
    }

    return { error: null, role: role || undefined, user: data.user as any };
  };

  const signUp = async (username: string, password: string, name?: string) => {
    const { data, error } = await supabase.auth.signUp({
      username,
      password,
      options: { data: { name } }
    } as any);

    if (error) {
      return { error: error };
    }

    // Do not set session/user in context so user must explicitly sign in from scratch
    return { error: null, user: data?.user as any };
  };

  // ─── signOut ──────────────────────────────────────────────────────────────────
  const signOut = async () => {
    try {
      clearAuthState();
      await supabase.auth.signOut({ scope: 'global' });
    } catch {
      clearAuthState();
    } finally {
      if (typeof window !== 'undefined') {
        window.location.replace('/');
      }
    }
  };

  return (
    <AuthContext.Provider value={{
      user: user as any,
      session: session as any,
      loading,
      userRole,
      isAuthenticated,
      signIn,
      signUp,
      signOut,
      validateSession,
      refreshRole,
    }}>
      {children}
    </AuthContext.Provider>
  );
}

export function useAuth() {
  const context = useContext(AuthContext);
  if (context === undefined) {
    throw new Error('useAuth must be used within an AuthProvider');
  }
  return context;
}
